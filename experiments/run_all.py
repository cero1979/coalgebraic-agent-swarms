def _json_write(path: Path, value: Any) -> None:
    path.write_text(
        json.dumps(value, indent=2, sort_keys=True, ensure_ascii=True) + "\n",
        encoding="utf-8",
    )


def _csv_write(path: Path, header: Sequence[str], rows: Iterable[Sequence[Any]]) -> None:
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(header)
        writer.writerows(rows)


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _relative(path: Path) -> str:
    resolved = path.resolve()
    try:
        return resolved.relative_to(REPOSITORY_ROOT.resolve()).as_posix()
    except ValueError:
        return resolved.as_posix()


def _latex_escape(value: Any) -> str:
    replacements = {
        "\\": r"\textbackslash{}",
        "_": r"\_",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    return "".join(replacements.get(char, char) for char in str(value))


def _write_table(
    path: Path,
    *,
    columns: str,
    header: Sequence[Any],
    rows: Iterable[Sequence[Any]],
    caption: str,
    label: str,
    size: str = "small",
) -> None:
    lines = [
        "% Generated by experiments/run_all.py. Do not edit manually.",
        r"\begin{table}[tbp]",
        r"\centering",
        f"\\{size}",
        r"\setlength{\tabcolsep}{4pt}",
        f"\\begin{{tabular}}{{{columns}}}",
        r"\toprule",
        " & ".join(_latex_escape(item) for item in header) + r" \\",
        r"\midrule",
    ]
    lines.extend(
        " & ".join(_latex_escape(item) for item in row) + r" \\" for row in rows
    )
    lines.extend(
        [
            r"\bottomrule",
            r"\end{tabular}",
            f"\\caption{{{caption}}}",
            f"\\label{{{label}}}",
            r"\end{table}",
            "",
        ]
    )
    path.write_text("\n".join(lines), encoding="utf-8")


def _event_types(trace: Sequence[Mapping[str, Any]]) -> list[str]:
    return sorted(
        {
            str(event["event"])
            for event in trace
            if isinstance(event, Mapping) and isinstance(event.get("event"), str)
        }
    )


def run_e1(rules: dict[str, Any]) -> list[dict[str, Any]]:
    trace_paths = sorted(TRACE_DIR.glob("*.json"), key=lambda path: path.name)
    if len(trace_paths) != EXPECTED_CONFORMANCE_TOTAL:
        raise RuntimeError(
            f"E1 requires exactly {EXPECTED_CONFORMANCE_TOTAL} traces; found {len(trace_paths)}"
        )
    records: list[dict[str, Any]] = []
    for path in trace_paths:
        trace = load_json(path)
        expected_accepted = path.name.startswith("valid_")
        if not expected_accepted and not path.name.startswith("invalid_"):
            raise RuntimeError(f"E1 trace lacks valid_/invalid_ expectation prefix: {path.name}")
        checker_result = check_trace(copy.deepcopy(trace), copy.deepcopy(rules))
        accepted = bool(checker_result["accepted"])
        violations = checker_result.get("violations", [])
        records.append(
            {
                "trace": path.name,
                "expected_status": "accepted" if expected_accepted else "rejected",
                "observed_status": "accepted" if accepted else "rejected",
                "expectation_matched": accepted == expected_accepted,
                "event_count": len(trace),
                "event_types": _event_types(trace),
                "violation_codes": sorted(
                    {
                        str(item["code"])
                        for item in violations
                        if isinstance(item, Mapping) and item.get("code")
                    }
                ),
                "checker_result": checker_result,
            }
        )
    accepted_count = sum(item["observed_status"] == "accepted" for item in records)
    rejected_count = len(records) - accepted_count
    if accepted_count != EXPECTED_CONFORMANCE_ACCEPTED:
        raise RuntimeError(f"E1 expected 5 accepted traces; observed {accepted_count}")
    if rejected_count != EXPECTED_CONFORMANCE_REJECTED:
        raise RuntimeError(f"E1 expected 14 rejected traces; observed {rejected_count}")
    mismatches = [item["trace"] for item in records if not item["expectation_matched"]]
    if mismatches:
        raise RuntimeError(f"E1 expectation mismatches: {mismatches}")
    return records


def run_e2(rules: dict[str, Any]) -> list[dict[str, Any]]:
    from integrations.langgraph import available_workflows, run_workflow

    records: list[dict[str, Any]] = []
    for workflow in available_workflows():
        run_id = f"e2-{workflow}-run-001"
        framework_run = run_workflow(workflow, run_id)
        canonical_trace = framework_run["canonical_trace"]
        checker_result = check_trace(
            copy.deepcopy(canonical_trace), copy.deepcopy(rules)
        )
        if not checker_result.get("accepted", False):
            raise RuntimeError(
                f"E2 canonical trace for {workflow!r} was rejected: "
                f"{checker_result.get('violations', [])}"
            )
        records.append(
            {
                **framework_run,
                "run_count_for_workflow": 1,
                "run_count_rationale": (
                    "The workflow and local tools are deterministic; one execution "
                    "tests the sole configured path without inflating the sample count."
                ),
                "native_record_count": len(framework_run["native_stream"]),
                "canonical_event_count": len(canonical_trace),
                "canonical_event_types": _event_types(canonical_trace),
                "checker_result": checker_result,
            }
        )
    if len(records) != 3:
        raise RuntimeError(f"E2 requires three workflows; observed {len(records)}")
    return records


def run_e3(
    framework_records: Sequence[Mapping[str, Any]],
    rules: dict[str, Any],
) -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    for framework_record in framework_records:
        workflow = str(framework_record["workflow"])
        run_id = str(framework_record["run_id"])
        canonical_trace = copy.deepcopy(framework_record["canonical_trace"])
        base_result = check_trace(copy.deepcopy(canonical_trace), copy.deepcopy(rules))
        if not base_result.get("accepted", False):
            raise RuntimeError(f"E3 source trace for {workflow!r} is not accepted")
        cases = generate_mutation_cases_from_trace(
            canonical_trace,
            canonical_name=f"{workflow}:{run_id}",
            rules=rules,
        )
        if len(cases) != EXPECTED_MUTATIONS_PER_WORKFLOW:
            raise RuntimeError(
                f"E3 requires 14 mutations for {workflow!r}; observed {len(cases)}"
            )
        for case in cases:
            result = evaluate_mutation(case, rules, check_trace)
            strictly_detected = bool(
                not result["accepted"]
                and result["detected"]
                and result["expected_at_target_step"]
                and result["diagnostic_exact"]
                and result["diagnostic_count"] == 1
            )
            records.append(
                {
                    "workflow": workflow,
                    "source_run_id": run_id,
                    **result,
                    "strictly_detected": strictly_detected,
                    "mutated_trace": case.trace,
                }
            )
    failures = [
        f"{item['workflow']}:{item['mutation']}" for item in records if not item["strictly_detected"]
    ]
    if failures:
        raise RuntimeError(f"E3 mutations without one exact target diagnostic: {failures}")
    expected_total = len(framework_records) * EXPECTED_MUTATIONS_PER_WORKFLOW
    if len(records) != expected_total:
        raise RuntimeError(f"E3 requires {expected_total} cases; observed {len(records)}")
    return records


def _git_value(*args: str) -> str | None:
    try:
        result = subprocess.run(
            ["git", *args],
            cwd=REPOSITORY_ROOT,
            check=True,
            capture_output=True,
            text=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return None
    return result.stdout.strip() or None


def _package_version(name: str) -> str | None:
    try:
        return version(name)
    except PackageNotFoundError:
        return None


def build_environment(scaling_report: Mapping[str, Any]) -> dict[str, Any]:
    environment = dict(scaling_report["environment"])
    environment.update(
        {
            "repository_commit": _git_value("rev-parse", "HEAD"),
            "repository_branch": _git_value("branch", "--show-current"),
            "repository_worktree_dirty": bool(_git_value("status", "--porcelain")),
            "dependencies": {
                "langgraph": _package_version("langgraph"),
                "langchain-core": _package_version("langchain-core"),
                "pydantic": _package_version("pydantic"),
            },
            "timing_scope": (
                "One check_trace call, including rule indexing; trace and rules deep copies "
                "are prepared before the timer starts."
            ),
        }
    )
    return environment


def build_summary(
    e1: Sequence[Mapping[str, Any]],
    e2: Sequence[Mapping[str, Any]],
    e3: Sequence[Mapping[str, Any]],
    e4: Mapping[str, Any],
) -> dict[str, Any]:
    e1_accepted = sum(item["observed_status"] == "accepted" for item in e1)
    e3_detected = sum(bool(item["strictly_detected"]) for item in e3)
    mutation_groups: dict[tuple[str, str], list[Mapping[str, Any]]] = {}
    for item in e3:
        key = (str(item["mutation"]), str(item["expected_code"]))
        mutation_groups.setdefault(key, []).append(item)
    mutation_by_category = [
        {
            "mutation": mutation,
            "obligation_code": code,
            "generated": len(items),
            "correctly_rejected": sum(
                not bool(item["accepted"]) and bool(item["detected"])
                for item in items
            ),
            "strictly_detected": sum(
                bool(item["strictly_detected"]) for item in items
            ),
            "unexpectedly_accepted": sum(bool(item["accepted"]) for item in items),
        }
        for (mutation, code), items in mutation_groups.items()
    ]
    return {
        "schema_version": 1,
        "generated_at_utc": e4["environment"]["captured_at_utc"],
        "E1_conformance": {
            "traces": len(e1),
            "accepted": e1_accepted,
            "rejected": len(e1) - e1_accepted,
            "expectation_matches": sum(bool(item["expectation_matched"]) for item in e1),
            "events": sum(int(item["event_count"]) for item in e1),
            "rejection_codes_covered": sorted(
                {
                    code
                    for item in e1
                    for code in item.get("violation_codes", [])
                }
            ),
        },
        "E2_framework_validation": {
            "framework": "LangGraph",
            "workflows": len(e2),
            "runs": len(e2),
            "accepted": sum(bool(item["checker_result"]["accepted"]) for item in e2),
            "native_records": sum(int(item["native_record_count"]) for item in e2),
            "canonical_events": sum(int(item["canonical_event_count"]) for item in e2),
            "valid_trace_acceptance_rate": (
                sum(bool(item["checker_result"]["accepted"]) for item in e2) / len(e2)
                if e2
                else 0.0
            ),
        },
        "E3_mutation_testing": {
            "source_traces": len(e2),
            "categories_per_source": EXPECTED_MUTATIONS_PER_WORKFLOW,
            "generated": len(e3),
            "strictly_detected": e3_detected,
            "strict_detection_rate": e3_detected / len(e3) if e3 else 0.0,
            "obligation_codes_covered": sorted(
                {str(item["expected_code"]) for item in e3}
            ),
            "by_category": mutation_by_category,
        },
        "E4_scaling": {
            "workload": str(e4["workload"]),
            "lengths": list(e4["lengths"]),
            "repetitions": int(e4["repetitions"]),
            "warmups": int(e4["warmups"]),
            "samples": [
                {
                    "events": int(sample["events"]),
                    "event_type_counts": dict(sample["event_type_counts"]),
                    "median_seconds": float(sample["median_seconds"]),
                    "iqr_seconds": float(sample["iqr_seconds"]),
                    "events_per_second": float(sample["events_per_second"]),
                }
                for sample in e4["samples"]
            ],
        },
    }


def write_result_files(
    results_dir: Path,
    *,
    e1: Sequence[Mapping[str, Any]],
    e2: Sequence[Mapping[str, Any]],
    e3: Sequence[Mapping[str, Any]],
    e4: Mapping[str, Any],
    summary: Mapping[str, Any],
    environment: Mapping[str, Any],
    selected: frozenset[str] = frozenset(
        {"conformance", "framework", "mutations", "benchmark", "metadata"}
    ),
) -> list[Path]:
    emitted: list[Path] = []

    def json_file(name: str, value: Any) -> Path:
        path = results_dir / name
        _json_write(path, value)
        emitted.append(path)
        return path

    if "conformance" in selected:
        json_file("conformance_results.json", list(e1))
        conformance_csv = results_dir / "conformance_results.csv"
        _csv_write(
            conformance_csv,
            (
                "trace",
                "expected_status",
                "observed_status",
                "expectation_matched",
                "events",
                "violation_codes",
            ),
            (
                (
                    item["trace"],
                    item["expected_status"],
                    item["observed_status"],
                    item["expectation_matched"],
                    item["event_count"],
                    ";".join(item["violation_codes"]),
                )
                for item in e1
            ),
        )
        emitted.append(conformance_csv)

    if "framework" in selected:
        json_file("framework_runs.json", list(e2))
        framework_csv = results_dir / "framework_runs.csv"
        _csv_write(
            framework_csv,
            (
                "workflow",
                "run_id",
                "langgraph_version",
                "native_records",
                "canonical_events",
                "event_types",
                "accepted",
            ),
            (
                (
                    item["workflow"],
                    item["run_id"],
                    item["langgraph_version"],
                    item["native_record_count"],
                    item["canonical_event_count"],
                    ";".join(item["canonical_event_types"]),
                    item["checker_result"]["accepted"],
                )
                for item in e2
            ),
        )
        emitted.append(framework_csv)

    if "mutations" in selected:
        json_file("mutation_results.json", list(e3))
        mutation_csv = results_dir / "mutation_results.csv"
        _csv_write(
            mutation_csv,
            (
                "workflow",
                "source_run_id",
                "mutation",
                "expected_code",
                "target_step",
                "observed_codes",
                "diagnostic_count",
                "strictly_detected",
            ),
            (
                (
                    item["workflow"],
                    item["source_run_id"],
                    item["mutation"],
                    item["expected_code"],
                    item["target_step"],
                    ";".join(item["observed_codes"]),
                    item["diagnostic_count"],
                    item["strictly_detected"],
                )
                for item in e3
            ),
        )
        emitted.append(mutation_csv)

    if "benchmark" in selected:
        json_file("runtime_results.json", dict(e4))
        json_file("environment.json", dict(environment))
        runtime_csv = results_dir / "runtime_results.csv"
        _csv_write(
            runtime_csv,
            (
                "events",
                "message_events",
                "handoff_events",
                "repetitions",
                "median_seconds",
                "q1_seconds",
                "q3_seconds",
                "iqr_seconds",
                "events_per_second",
                "durations_seconds",
            ),
            (
                (
                    sample["events"],
                    sample["event_type_counts"]["message"],
                    sample["event_type_counts"]["handoff"],
                    sample["repetitions"],
                    sample["median_seconds"],
                    sample["q1_seconds"],
                    sample["q3_seconds"],
                    sample["iqr_seconds"],
                    sample["events_per_second"],
                    ";".join(str(value) for value in sample["durations_seconds"]),
                )
                for sample in e4["samples"]
            ),
        )
        emitted.append(runtime_csv)

    if "metadata" in selected:
        json_file("summary.json", dict(summary))
    return emitted


